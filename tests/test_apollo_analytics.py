def test_sync_requires_api_key(monkeypatch):
    # apollo_client loads .env on import; make sure no real key leaks in from
    # the environment, otherwise the missing-key branch is never exercised.
    monkeypatch.delenv("APOLLO_API_KEY", raising=False)
    conn = _sqlite_conn()
    with pytest.raises(aa.ApolloAnalyticsError):
        aa.sync_analytics_report(conn, key="", _get=lambda *a, **kw: {})


def test_sync_sweeps_pages_saves_report_and_folds_outcomes(monkeypatch):
    conn = _sqlite_conn()
    conn.execute("INSERT INTO leads (id, session_id, email) VALUES (1, 1, 'alice@co.com')")
    conn.commit()
    monkeypatch.setattr(aa, "ensure_report_table", lambda c: None)

    pages = iter([
        {"emailer_messages": [
            {"id": "m1", "to_email": "alice@co.com", "status": "opened",
             "sent_at": "2026-09-05T10:00:00Z", "opens": 1, "clicks": 1, "replied": True,
             "reply_class": "willing_to_meet", "emailer_campaign_id": "c1"},
            {"id": "m2", "to_email": "nobody@nowhere.com", "status": "delivered",
             "sent_at": "2026-09-05T11:00:00Z"},
            {"id": "m3", "to_email": "old@co.com", "status": "delivered",
             "sent_at": "2020-01-01T10:00:00Z"},  # older than the window -> skipped
            {"id": "m4", "status": "drafted"},     # not sent -> skipped
        ], "pagination": {"total_pages": 2}},
        {"emailer_messages": [], "pagination": {"total_pages": 2}},
    ])

    def _fake_get(path, params, key):
        assert path == aa.SEARCH_EMAILS_PATH
        assert key == "secret"
        return next(pages)

    result = aa.sync_analytics_report(conn, key="secret", days=7, _get=_fake_get)
    assert result["messages"] == 2
    assert result["matched"] == 1
    assert result["unmatched"] == 1
    assert result["replied"] == 1
    assert result["opened"] == 1 and result["clicked"] == 1

    # Raw report rows persisted.
    report = conn.execute("SELECT * FROM apollo_analytics_sync_report").fetchall()
    assert len(report) == 2
    assert {r["apollo_message_id"] for r in report} == {"m1", "m2"}

    # lead_outcomes folded: m1 mapped to lead 1.
    outcome = conn.execute("SELECT * FROM lead_outcomes WHERE lead_id = 1").fetchone()
    assert outcome["replied"] == 1
    assert outcome["reply_sentiment"] == "willing_to_meet"
    assert outcome["email"] == "alice@co.com"

    # Re-running is idempotent: no new report row, same outcome.
    pages2 = iter([{"emailer_messages": [
        {"id": "m1", "to_email": "alice@co.com", "status": "opened",
         "sent_at": "2026-09-05T10:00:00Z", "opens": 1, "replied": True}],
        "pagination": {"total_pages": 1}}])
    aa.sync_analytics_report(conn, key="secret", days=7,
                             _get=lambda *a, **kw: next(pages2))
    assert conn.execute("SELECT COUNT(*) FROM apollo_analytics_sync_report").fetchone()[0] == 2
    assert conn.execute("SELECT COUNT(*) FROM lead_outcomes").fetchone()[0] == 1