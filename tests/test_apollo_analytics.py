def test_build_sync_report_payload_custom_window():
    p = aa.build_sync_report_payload(start="2026-08-01", end="2026-08-31", group_by="emailer_campaign_id")
    assert p["date_ranges"] == [{"modality": "custom_range"}]
    assert p["filters"] == {"smart_datetime_range": {"min": "2026-08-01", "max": "2026-08-31"}}
    assert p["group_by"] == [{"name": "emailer_campaign_id"}]
    assert {m["value"] for m in p["metrics"]} == {
        "num_emails_sent", "num_emails_opened", "num_emails_clicked", "num_emails_replied"}


def test_build_sync_report_payload_preset_window():
    p = aa.build_sync_report_payload()
    assert p["date_ranges"][0]["modality"] == "last_30_days"
    assert p["filters"] == {}
    assert p["group_by"] == []


def test_parse_sync_report_flattens_buckets_and_drops_total():
    data = {"response": {"table_response": {"emailer_campaign_id": {"buckets": [
        {"key": "c1", "readable_key": "Q2 Outreach", "num_emails_sent": 100,
         "num_emails_opened": 60, "num_emails_clicked": 10, "num_emails_replied": 8},
        {"key": "total", "readable_key": "Total", "num_emails_sent": 100, "num_emails_replied": 8},
    ]}}}}
    rows = aa.parse_sync_report(data)
    assert len(rows) == 1
    assert rows[0]["key"] == "c1"
    assert rows[0]["num_emails_sent"] == 100
    assert rows[0]["num_emails_replied"] == 8


