"""apollo_analytics (Task 13) — offline guards.

DDL must be PG-identity (sqlite can't run it — same guard as campaigns). HTTP is
isolated in _get, so the sweep + fold runs against a sqlite harness with a
stubbed ensure_report_table and its own compat tables (the project's standard
pattern, see test_campaigns.py / test_campaign_flow.py).
"""
import sqlite3

import pytest

import apollo_analytics as aa


class _CapturingConn:
    def __init__(self):
        self.executed = []

    def execute(self, sql, params=None):
        self.executed.append(sql)
        return self

    def commit(self):
        pass


def test_ensure_report_table_ddl_is_postgres_only():
    conn = _CapturingConn()
    aa.ensure_report_table(conn)
    ddl = conn.executed[0]
    assert "AUTOINCREMENT" not in ddl
    assert "?" not in ddl
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl
    assert ddl.startswith("CREATE TABLE IF NOT EXISTS apollo_analytics_sync_report")


def test_ensure_report_table_is_idempotent_via_schema_and_guard():
    # Both the startup migration (db._schema_sql) and the module guard share
    # the same table name; dupes must never be created.
    assert "apollo_analytics_sync_report" in __import__("db")._schema_sql()


def _sqlite_conn():
    conn = sqlite3.connect(":memory:")
    conn.row_factory = sqlite3.Row
    conn.execute("""
        CREATE TABLE leads (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            session_id INTEGER, email TEXT, email_sent_at TEXT
        )
    """)
    conn.execute("""
        CREATE TABLE lead_outcomes (
            lead_id INTEGER PRIMARY KEY,
            email TEXT, channel TEXT, recipe_id INTEGER, sent_at TEXT,
            opened INTEGER, clicked INTEGER, replied INTEGER, reply_sentiment TEXT,
            meeting_booked INTEGER, closed_won INTEGER, revenue REAL,
            created_at TEXT, updated_at TEXT
        )
    """)
    conn.execute("""
        CREATE TABLE apollo_analytics_sync_report (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            month TEXT, fetched_at TEXT, apollo_message_id TEXT,
            to_email TEXT, emailer_campaign_id TEXT, sent_at TEXT, status TEXT,
            opened INTEGER, clicked INTEGER, replied INTEGER,
            reply_sentiment TEXT, raw_json TEXT,
            UNIQUE(month, apollo_message_id)
        )
    """)
    conn.commit()
    return conn


