def test_parse_outreach_email_maps_flags_and_sentiment():
    msg = {
        "id": "m1",
        "to_email": "alice@co.com",
        "status": "opened",
        "sent_at": "2026-09-01T10:00:00Z",
        "opens": 2,
        "clicks": 1,
        "replied": True,
        "reply_class": "willing_to_meet",
        "emailer_campaign_id": "camp-7",
    }
    r = aa.parse_outreach_email(msg)
    assert r["email"] == "alice@co.com"
    assert r["opened"] == 1 and r["clicked"] == 1 and r["replied"] == 1
    assert r["reply_sentiment"] == "willing_to_meet"
    assert r["campaign_id"] == "camp-7"


def test_parse_outreach_email_falls_back_to_recipients():
    msg = {"id": "m2", "recipients": [{"email": "Bob@X.COM ", "raw_name": "Bob"}],
           "status": "delivered", "opened_at": None}
    r = aa.parse_outreach_email(msg)
    assert r["email"] == "bob@x.com"  # lowercased + stripped
    assert r["opened"] == 0 and r["clicked"] == 0 and r["replied"] == 0


def test_message_skippable_drafts_scheduled():
    assert aa._message_skippable({"status": "scheduled"})
    assert aa._message_skippable({"status": "drafted"})
    assert not aa._message_skippable({"status": "delivered"})
    assert not aa._message_skippable({"status": None})


